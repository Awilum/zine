import fs from 'node:fs';
import { TEMPLATE_PATH } from './paths.js';
import { getFormatOptions } from './validation.js';
export const typstString = (s) =>
  String(s ?? '')
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\n', '\\n');
export function assembleTypst(book, body, publication) {
  const f = getFormatOptions(book);
  const p = book.pagination || {};
  const pos = p.position || 'bottom-center';
  const enabled = p.enabled !== false;
  return `// Generated by ZINE ${book.id}\n${fs.readFileSync(TEMPLATE_PATH, 'utf8')}\n#show: zine.with(paper: "${f.paper}", flipped: ${f.flipped}, margin-top: ${f.margins.top}mm, margin-right: ${f.margins.right}mm, margin-bottom: ${f.margins.bottom}mm, margin-left: ${f.margins.left}mm, font: "${typstString(f.font)}", pagination-enabled: ${enabled}, pagination-position: "${pos}")\n${body}`;
}
